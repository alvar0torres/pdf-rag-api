from uuid import uuid4

from qdrant_client import QdrantClient, models

COLLECTION_NAME = "document_chunks"
VECTOR_SIZE = (
    1536  # Size of the embeddings generated by OpenAI's text-embedding-3-small model
)

client = QdrantClient(path="qdrant_data")

if not client.collection_exists(collection_name=COLLECTION_NAME):
    client.create_collection(
        collection_name=COLLECTION_NAME,
        vectors_config=models.VectorParams(
            size=VECTOR_SIZE, distance=models.Distance.COSINE
        ),
    )

client.create_payload_index(
    collection_name=COLLECTION_NAME,
    field_name="text",
    field_schema=models.TextIndexParams(
        type="text",
        tokenizer=models.TokenizerType.WORD,
        lowercase=True,
        scoring=True,
    ),
)


def store_chunks(
    chunks: list[dict[str, str | int]],
    embeddings: list[list[float]],
) -> None:
    if len(chunks) != len(embeddings):
        raise ValueError("There must be one embedding for each chunk.")

    points = [
        models.PointStruct(
            id=str(uuid4()),
            vector=embedding,
            payload=chunk,
        )
        for chunk, embedding in zip(chunks, embeddings, strict=True)
    ]

    client.upsert(collection_name=COLLECTION_NAME, points=points)


def search_chunks(
    embedding: list[float],
    limit: int = 5,
) -> list[models.ScoredPoint]:
    response = client.query_points(
        collection_name=COLLECTION_NAME,
        query=embedding,
        limit=limit,
        with_payload=True,
    )

    return response.points


def search_keyword_chunks(
    query: str,
    limit: int = 5,
) -> list[models.ScoredPoint]:
    response = client.query_points(
        collection_name=COLLECTION_NAME,
        query=models.TextQuery(text=query),
        using="text",
        limit=limit,
        with_payload=True,
    )

    return response.points


def delete_document_chunks(file_name: str) -> None:
    client.delete(
        collection_name=COLLECTION_NAME,
        points_selector=models.FilterSelector(
            filter=models.Filter(
                must=[
                    models.FieldCondition(
                        key="file_name",
                        match=models.MatchValue(value=file_name),
                    )
                ]
            )
        ),
    )
